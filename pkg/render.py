
# -*- coding: utf-8 -*-
"""逐例 Markdown 渲染（本单唯一需要人工措辞的文件）。"""
import engine as E


def md_head():
    return ["# 历史会员导入跑批记录（全部虚构数据）", "",
            "前置数据：100 家企业、260 名联系人；其中 5 行信用代码错误、3 行重复企业、6 行联系人缺手机号。",
            "导入结果：成功 92 家、错误报告 8 行；缺手机号的 6 行联系人**导入成功**，只在完整度上扣分。", "",
            "关键字段完整度（6 项非空比例）记录单位为企业，联系人姓名与手机号取该企业的主联系人。", "",
            "> 企业名、信用代码、人名、手机号与全部字段取值均为虚构；"
            "手机号落在不可分配的测试号段，不含真实个人信息与企业信息，也不含客户名称。", ""]


def md_section(c):
    return ["## 第 %d 行 %s" % (c["row"], c["企业名称"]), "",
            "| 项 | 值 |", "| --- | --- |",
            "| Excel 行号 | %d |" % c["row"],
            "| 企业名称 | %s |" % c["企业名称"],
            "| 信用代码 | `%s`（%d 位） |" % (c["信用代码"], len(c["信用代码"])),
            "| 产业方向 | %s |" % c["产业方向"],
            "| 会籍档位 | %s |" % c["会籍档位"],
            "| 所在城市 | %s |" % c["所在城市"],
            "| 成立年份 | %s |" % c["成立年份"], "",
            "校验：信用代码合法 = %s；若与前序行重复则该行判为重复企业。"
            % ("是" if E.RE_CREDIT.match(c["信用代码"]) else "否"), ""]
